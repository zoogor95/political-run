/* global process, URL, console */
// Packs the built game (apps/web/dist, or the folder given) into files.gen.ts for the site Worker (worker.ts).
// The files travel inside the Worker's code, so the site deploys with a plain `wrangler deploy`.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = process.argv[2] ?? new URL("../dist", import.meta.url).pathname;
const TEXT = /\.(html|js|css|json|svg|txt|webmanifest)$/;
const files = {};
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path);
    else {
      const key = "/" + relative(root, path).split("\\").join("/");
      files[key] = TEXT.test(name) ? { text: readFileSync(path, "utf8") } : { base64: readFileSync(path).toString("base64") };
    }
  }
};
walk(root);
if (!files["/index.html"]) throw new Error(`No index.html in ${root}: build the game first`);
writeFileSync(new URL("./files.gen.ts", import.meta.url), `// Generated by build.mjs from ${relative(process.cwd(), root) || "."}; not committed.\nexport default ${JSON.stringify(files)} as Record<string, { text?: string; base64?: string }>;\n`);
console.log(`Packed ${Object.keys(files).length} files`);
